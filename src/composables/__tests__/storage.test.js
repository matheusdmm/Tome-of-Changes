import { describe, it, expect, beforeEach, vi, afterEach } from 'vitest'
const entry = { slug: 'fireball', name: 'Fireball', category: 'Spell' }
beforeEach(() => { localStorage.clear(); vi.resetModules() })
afterEach(() => vi.restoreAllMocks())
describe('persistent data recovery and deletion', () => {
  it('migrates legacy arrays, persists changes immediately, and rehydrates versioned data', async () => {
    localStorage.setItem('tome-favorites', JSON.stringify([entry]))
    let { useFavorites } = await import('../useFavorites.js')
    expect(useFavorites().favorites.value[0].name).toBe('Fireball')
    useFavorites().toggleFavorite({ ...entry, slug: 'hex', name: 'Hex' })
    expect(JSON.parse(localStorage.getItem('tome-favorites')).version).toBe(1)
    vi.resetModules()
    ;({ useFavorites } = await import('../useFavorites.js'))
    expect(useFavorites().favorites.value).toHaveLength(2)
  })
  for (const raw of ['{invalid', '{}', 'null', '[{}]', '{"version":2,"data":[]}']) it(`recovers invalid favorites: ${raw}`, async () => {
    localStorage.setItem('tome-favorites', raw)
    const { useFavorites } = await import('../useFavorites.js')
    const { storageError } = await import('../useStorage.js')
    expect(useFavorites().favorites.value).toEqual([])
    expect(storageError.value).toContain('could not be read')
  })
  it('clears all reactive state and never resurrects deleted entries on later edits', async () => {
    const { useFavorites } = await import('../useFavorites.js')
    const { useNotes } = await import('../useNotes.js')
    const { useRecentlyViewed } = await import('../useRecentlyViewed.js')
    const { resetStoredData } = await import('../useStorage.js')
    const favorites = useFavorites(), notes = useNotes(), recent = useRecentlyViewed()
    favorites.toggleFavorite(entry); notes.saveNote(entry, 'private'); recent.addRecentlyViewed(entry)
    expect(resetStoredData()).toBe(true)
    expect(favorites.favorites.value).toEqual([])
    expect(notes.getNote(entry)).toBe('')
    expect(recent.recentlyViewed.value).toEqual([])
    expect(localStorage.getItem('tome-favorites')).toBeNull()
    favorites.toggleFavorite({ ...entry, name: 'Hex', slug: 'hex' })
    expect(JSON.parse(localStorage.getItem('tome-favorites')).data.map(e => e.name)).toEqual(['Hex'])
  })
  it('keeps working when storage reads or writes are blocked', async () => {
    vi.spyOn(Storage.prototype, 'getItem').mockImplementation(() => { throw new Error('blocked') })
    vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => { throw new Error('quota') })
    const { useFavorites } = await import('../useFavorites.js')
    const { storageError } = await import('../useStorage.js')
    expect(() => useFavorites().toggleFavorite(entry)).not.toThrow()
    expect(useFavorites().favorites.value).toHaveLength(1)
    expect(storageError.value).toContain('could not be saved')
  })
  it('reports deletion failure rather than claiming persistent data is gone', async () => {
    await import('../useFavorites.js')
    vi.spyOn(Storage.prototype, 'removeItem').mockImplementation(() => { throw new Error('blocked') })
    const { resetStoredData } = await import('../useStorage.js')
    expect(resetStoredData()).toBe(false)
  })
  it('receives another tab’s writes and deletions without writing them back', async () => {
    const { useFavorites } = await import('../useFavorites.js')
    const write = vi.spyOn(Storage.prototype, 'setItem')
    const favorites = useFavorites()
    window.dispatchEvent(new StorageEvent('storage', { key: 'tome-favorites', newValue: JSON.stringify({ version: 1, data: [entry] }) }))
    expect(favorites.favorites.value[0].name).toBe('Fireball')
    expect(write).not.toHaveBeenCalled()
    window.dispatchEvent(new StorageEvent('storage', { key: 'tome-favorites', newValue: null }))
    expect(favorites.favorites.value).toEqual([])
  })
  it('reads and updates legacy source-keyed notes using a stable identity', async () => {
    localStorage.setItem('tome-notes', JSON.stringify({ 'Spell-srd_fireball': 'old note' }))
    const { useNotes } = await import('../useNotes.js')
    const notes = useNotes(), migrated = { ...entry, v2014: { key: 'srd_fireball' } }
    expect(notes.getNote(migrated)).toBe('old note')
    notes.saveNote(migrated, '')
    expect(notes.getNote(migrated)).toBe('')
  })
})
