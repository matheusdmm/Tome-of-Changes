import { describe, it, expect, beforeEach, afterEach, vi } from 'vitest'
import fixtures from './fixtures/open5e.json'
vi.mock('@vercel/analytics', () => ({ track: vi.fn() }))
let app, host
const flush = async () => { for (let i = 0; i < 5; i++) await new Promise(resolve => setTimeout(resolve, 0)) }
const button = text => [...host.querySelectorAll('button')].find(node => node.textContent.trim() === text)
function input(node, value) { node.value = value; node.dispatchEvent(new Event('input', { bubbles: true })) }
function change(node, value) { node.value = value; node.dispatchEvent(new Event('change', { bubbles: true })) }
function check(node, checked) { node.checked = checked; node.dispatchEvent(new Event('change', { bubbles: true })) }
beforeEach(() => { localStorage.clear(); vi.resetModules() })
afterEach(() => { app?.unmount(); host?.remove(); vi.unstubAllGlobals(); vi.restoreAllMocks() })
const entry = { name: 'Counterspell', slug: 'counterspell', category: 'Spell', v2014: fixtures.Spell['srd-2014'], v2024: fixtures.Spell['srd-2024'] }
async function mount(component, path = '/favorites', props = {}) {
  const { createApp } = await import('vue'), { createRouter, createMemoryHistory } = await import('vue-router')
  const dummy = { template: '<div />' }
  const router = createRouter({ history: createMemoryHistory(), routes: [
    { path: '/', name: 'home', component: dummy }, { path: '/favorites', name: 'favorites', component: dummy },
    { path: '/browse/:category', name: 'browse', component: dummy }, { path: '/compare/:category/:query(.*)', name: 'compare', component: dummy },
  ] })
  await router.push(path); await router.isReady()
  host = document.createElement('div'); document.body.append(host)
  app = createApp(component, props); app.use(router); app.mount(host); await flush()
  return router
}
describe('feature journeys', () => {
  it('shows both source versions and toggles changed statistics without losing full text', async () => {
    const { default: EntryCard } = await import('../../components/EntryCard.vue')
    await mount(EntryCard, '/compare/Spell/Counterspell', { entry })
    expect(host.textContent).toContain('SRD 5.1 · 2014 rules')
    expect(host.textContent).toContain('SRD 5.2 · 2024 rules')
    expect([...host.querySelectorAll('a')].some(link => link.href === fixtures.Spell['srd-2024'].document.permalink)).toBe(true)
    expect(host.textContent).toContain('Range')
    button('Changes only').click(); await flush()
    expect(button('Changes only').getAttribute('aria-pressed')).toBe('true')
    expect(host.querySelector('table').textContent).not.toContain('Range')
    expect(host.querySelector('table').textContent).toContain('Saving throw')
    button('Full comparison').click(); await flush()
    expect(host.querySelector('table').textContent).toContain('Range')
    expect(host.textContent).toContain('At higher levels')
  })
  it('creates a collection, assigns an existing favorite, reviews it, and renames it', async () => {
    const { default: Favorites } = await import('../../views/FavoritesView.vue')
    const { useFavorites } = await import('../useFavorites.js'), { useCollections } = await import('../useCollections.js')
    useFavorites().addFavorite(entry)
    const router = await mount(Favorites)
    input(host.querySelector('input[placeholder]'), 'Friday campaign')
    host.querySelector('form').dispatchEvent(new Event('submit', { bubbles: true, cancelable: true })); await flush()
    const collectionId = router.currentRoute.value.query.collection
    expect(collectionId).toBeTruthy()
    await router.push('/favorites'); await flush()
    const picker = [...host.querySelectorAll('details')].find(node => node.querySelector('summary')?.textContent === 'Collections')
    picker.open = true; picker.dispatchEvent(new Event('toggle')); await flush()
    const membership = [...host.querySelectorAll('label')].find(label => label.textContent.trim() === 'Friday campaign').querySelector('input')
    check(membership, true); await flush()
    expect(useFavorites().favorites.value).toHaveLength(1)
    await router.push({ name: 'favorites', query: { collection: collectionId } }); await flush()
    const reviewed = host.querySelector('input[aria-label="Mark Counterspell as reviewed"]')
    check(reviewed, true); await flush()
    expect(host.textContent).toContain('1 of 1 entries reviewed')
    const collectionNote = host.querySelector('textarea[maxlength="10000"]')
    input(collectionNote, 'Bring the new character sheet')
    input(host.querySelector('input[id$="-rename"]'), 'Mira')
    button('Rename collection').click(); await flush()
    expect(useCollections().collections.value[0]).toMatchObject({ name: 'Mira', note: 'Bring the new character sheet' })
    change([...host.querySelectorAll('select')].find(node => [...node.options].some(o => o.value === 'pending')), 'pending'); await flush()
    expect(host.textContent).toContain('No entries match this collection view')
    expect(useCollections().entriesFor(collectionId)).toHaveLength(1)
  })
  it('previews imports without mutation and replaces only after the explicit action', async () => {
    const { default: Backup } = await import('../../components/BackupControls.vue')
    const { useFavorites } = await import('../useFavorites.js'), { useNotes } = await import('../useNotes.js')
    const { createBackup } = await import('../../utils/backup.js')
    useFavorites().addFavorite(entry); useNotes().saveNote(entry, 'Imported note')
    const file = JSON.stringify(createBackup())
    useFavorites().addFavorite({ ...entry, name: 'Other', slug: 'other' }); useNotes().saveNote(entry, 'Current note')
    await mount(Backup)
    const upload = host.querySelector('input[type="file"]')
    Object.defineProperty(upload, 'files', { configurable: true, value: [{ size: file.length, text: async () => file }] })
    upload.dispatchEvent(new Event('change', { bubbles: true })); await flush()
    expect(host.textContent).toContain('Ready to import 1 favorites, 1 notes, and 0 collections')
    expect(useFavorites().favorites.value).toHaveLength(2)
    expect(useNotes().getNote(entry)).toBe('Current note')
    check(host.querySelector('input[type="radio"][value="replace"]'), true); await flush()
    button('Replace saved data').click(); await flush()
    expect(host.textContent).toContain('Import complete')
    expect(useFavorites().favorites.value).toHaveLength(1)
    expect(useNotes().getNote(entry)).toBe('Imported note')
    Object.defineProperty(upload, 'files', { configurable: true, value: [{ size: 4, text: async () => 'bad' }] })
    upload.dispatchEvent(new Event('change', { bubbles: true })); await flush()
    expect(host.textContent).toContain('Select a valid JSON backup file')
    expect(button('Replace saved data')).toBeUndefined()
    expect(useFavorites().favorites.value).toHaveLength(1)
  })
  it('keeps collection memberships until favorite removal is confirmed', async () => {
    const { default: EntryCard } = await import('../../components/EntryCard.vue')
    const { useFavorites } = await import('../useFavorites.js'), { useCollections } = await import('../useCollections.js')
    const { useNotes } = await import('../useNotes.js')
    const library = useCollections(), favorites = useFavorites()
    const id = library.createCollection('Campaign')
    library.toggleMembership(id, entry); useNotes().saveNote(entry, 'Keep this note')
    await mount(EntryCard, '/compare/Spell/Counterspell', { entry })
    button('♥ Saved').click(); await flush()
    expect(favorites.isFavorite(entry)).toBe(true)
    expect(library.contains(id, entry)).toBe(true)
    button('Cancel removal').click(); await flush()
    expect(button('Confirm removal')).toBeUndefined()
    button('♥ Saved').click(); await flush()
    button('Confirm removal').click(); await flush()
    expect(favorites.isFavorite(entry)).toBe(false)
    expect(library.contains(id, entry)).toBe(false)
    expect(useNotes().getNote(entry)).toBe('Keep this note')
  })
  it('browses without a name, keeps filters in the URL, and pages without refetching', async () => {
    const records = doc => Array.from({ length: 13 }, (_, index) => ({ key: `${doc}_${index}`, document: { key: doc }, name: `Entry ${index}`, desc: 'Rules', level: index === 12 ? 2 : 1, school: { name: index === 12 ? 'Illusion' : 'Evocation' } }))
    vi.stubGlobal('fetch', vi.fn(async url => ({ ok: true, json: async () => ({ results: records(new URL(url).searchParams.get('document__key__in')) }) })))
    const { default: Search } = await import('../../views/SearchView.vue')
    const router = await mount(Search, '/browse/Spell?level=1&school=evocation')
    expect(host.textContent).toContain('12 matches out of 13 loaded entries')
    expect(host.querySelector('select[aria-label="Spell school"]').value).toBe('Evocation')
    expect(host.querySelectorAll('[aria-label="Comparison reading mode"]')).toHaveLength(10)
    button('Next').click(); await flush()
    expect(router.currentRoute.value.query).toMatchObject({ level: '1', school: 'evocation', page: '2' })
    expect(host.querySelectorAll('[aria-label="Comparison reading mode"]')).toHaveLength(2)
    change(host.querySelector('select[aria-label="Spell level"]'), '2'); await flush()
    expect(router.currentRoute.value.query.page).toBeUndefined()
    expect(host.textContent).toContain('0 matches out of 13 loaded entries')
    button('Clear filters').click(); await flush()
    expect(host.textContent).toContain('13 entries found')
    expect(fetch).toHaveBeenCalledTimes(2)
  })
})
